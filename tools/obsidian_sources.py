def load_sources():
    allsrc = {}
    for rel in ("vkr/sources_main.py", "ekonomika/sources_econ.py", "ohrana_truda/sources_ot.py"):
        spec = importlib.util.spec_from_file_location(os.path.basename(rel)[:-3], os.path.join(DOCS, rel))
        m = importlib.util.module_from_spec(spec)
        with contextlib.redirect_stdout(io.StringIO()):
            spec.loader.exec_module(m)
        allsrc.update(m.SOURCES)
    return allsrc


def citations(num):
    """Предложения записки, где стоит ссылка с номером num."""
    pat = re.compile(r"\[([0-9, –-]+)\]")
    out = []
    for part, rel in PARTS:
        d = docx.Document(os.path.join(DOCS, rel))
        texts = [p.text for p in d.paragraphs] + [c.text for t in d.tables for r in t.rows for c in r.cells]
        seen = set()
        for t in texts:
            for sent in re.split(r"(?<=[.;:])\s+", t):
                for m in pat.finditer(sent):
                    nums = set()
                    for chunk in m.group(1).split(","):
                        chunk = chunk.strip()
                        if re.match(r"^\d+\s*[–-]\s*\d+$", chunk):
                            a, b = [int(x) for x in re.split(r"[–-]", chunk)]
                            nums.update(range(a, b + 1))
                        elif chunk.isdigit():
                            nums.add(int(chunk))
                    if num in nums and sent not in seen:
                        seen.add(sent)
                        out.append((part, sent.strip()))
    return out


def safe(name):
    return re.sub(r'[\\/:*?"<>|\[\]#^]', "", name)[:80].strip()   # [] и # ломают ссылки Obsidian


