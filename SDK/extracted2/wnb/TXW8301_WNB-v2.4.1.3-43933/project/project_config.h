// Причина: UART0 занимает PA_10/PA_11, а это HG_GMAC_MDIO_PIN и
// HG_GMAC_MDC_PIN (sys_config.h:230,233) в режиме HG_GMAC_IO_SIMULATION —
// MDIO дёргается программно по тем же GPIO. UART забрал пины, PHY не
// поднялся, hg_gmac_open вернул ошибку -> assert -> ребут каждые ~300 мс.
// Восстановление возможно только внешним программатором флеша.
//
// ESP32 подключён к UART1 модуля, а НЕ к UART0. Доказательство: консоль
// SDK печатает в uart1 (project/device.c:246, MACBUS_USB нигде не определён
// и в флагах сборки его нет), а мы читаем эту консоль через ESP32. Значит
// заводской дефолт ATCMD_UARTDEV = HG_UART1_DEVID (sys_config.h:75) для
// этой платы УЖЕ правильный — поэтому AT и работал на стоке 1.6.4.3.
//
// Ничего не переопределяем. Строку ниже не раскомментировать.
// #define ATCMD_UARTDEV    HG_UART0_DEVID   // НЕ ДЕЛАТЬ, см. выше

// GMAC_ENABLE / WIFI_BRIDGE_EN: ВОЗВРАЩЕНЫ К ЗАВОДСКИМ (обоих строк нет,
// в sys_config.h:99,103 они по умолчанию = 1). 2026-08-13.
//
// Отключение было реакцией на кирпич 11.08 — «уберём весь путь, на котором
// плата умерла». Но умерла она не от GMAC, а от того, что мы отдали UART0
// пины PA_10/PA_11, на которых GMAC-у нужен MDIO. С ATCMD и UART_P2P на
// UART1 конфликта нет вовсе, и заводская конфигурация с живым Ethernet —
// ровно та, которую вендор собирает и тестирует. Сток на обеих платах
// работает именно так.
//
// Обратная сторона отключения — риск того же класса, что нас уже убил:
// gmac_bus.c:59 делает dev_get(HG_GMAC_DEVID) без проверки на NULL, и при
// GMAC_ENABLE=0 устройства просто нет. Меньше отклонений от вендорского
// конфига — меньше шансов поймать ещё один assert на старте.
// (Блок регистрации e0 в main.c:227 сидит под #if 0 и роли не играет.)

// ШАГ 3 (13.08): включаем прозрачный режим.
// Шаг 2 закрыт — на ядре 2.4.1.3 утечка `no skb` не воспроизводится, линк
// между платами поднят, DHCP отработал. Теперь снимаем накладные расходы
// AT+TXDATA: вместо «команда + длина + payload» на каждый кусок кадра —
// сырой поток байт в UART1.
//
// Транспорт в 2.4 идёт поверх UDP (uart_p2p_init живёт в libnetutils, см.
// sdk/include/lib/net/utils.h:40), то есть требует поднятого IP-стека.
// Ещё одна причина, по которой GMAC и мост оставлены заводскими.
//
// Скорость на этом заходе НЕ поднимаем, см. комментарий к UART_P2P_BAUDRATE.
#define SYS_APP_UART_P2P    1       //=1，打开uart透传
//#define DIS_BOOT_PRINT            //关闭开机打印
#define UART_P2P_TIMER      HG_TIMER2_DEVID
#define UART_P2P_DEV        HG_UART1_DEVID   // UART1 — там, где ESP32. НЕ UART0.
// РАБОЧЕЕ ЗНАЧЕНИЕ 460800. Механика (проверено 13.08 по исходнику):
// project/atcmd.c:242 зовёт atcmd_uart_init(ATCMD_UARTDEV, 115200, ...)
// литералом, не через макрос. uart_p2p_init() поднимается позже, через
// UART_P2P_START_DELAY_MS, и переоткрывает ТОТ ЖЕ физический UART1 на
// UART_P2P_BAUDRATE — регистр скорости один на обоих потребителей,
// побеждает последний вызов.
//
// Из этого следует полезное свойство, а не проблема: аварийное окно с
// AT+NOP2P ВСЕГДА идёт на 115200, какую бы скорость мы ни поставили
// прозрачному режиму. Откат всегда доступен обычным терминалом.
// Обратная сторона: когда поднимем скорость, скетч ESP32 обязан открыть
// порт на 115200, пережить окно, и только потом переоткрыть на новой.
//
// Почему 460800, а не выше. У uart_p2p НЕТ управления потоком: ESP32 пишет,
// модуль обязан успевать, не успел — байты пропали молча. Единственный
// амортизатор — кольцо на 2 КБ (в исходнике 1.6 UARTP2P_RBSIZE=2048; в 2.4
// эта часть внутри libnetutils.a и не проверяема). Запас кольца по времени:
// 178 мс на 115200, 44 мс на 460800, 22 мс на 921600. Любая заминка радио
// длиннее запаса — потеря. Делитель UART при этом ни при чём: в hguart.c
// есть регистр DLF (дробная часть, шаг 1/16), погрешность на 921600 всё те
// же 0.16%, что и на 115200.
//
// Собранные варианты лежат в SDK/builds/ (115200/230400/460800 и
// 921600-EXPERIMENTAL). Пересобирать ради смены скорости не нужно — выбрать
// файл и залить. Значение здесь ДОЛЖНО совпадать с P2P_BAUD в скетчах
// examples/HalowVideoP2P_*.
// 230400, а не 460800. Причина не в наших измерениях, а в документации:
// вендор указывает для UART диапазон 9600-400K и предупреждает, что выше
// возможна некорректная работа. 460800 лежит за этой границей. Скетчи
// examples/HalowVideoP2P_* давно открывают порт на 230400 — теперь прошивка
// и код наконец говорят одно и то же (20.08: расхождение обнаружилось при
// разборе связи и стоило нам отдельной проверки).
// 02.09: 384000 — попытка поднять потолок транспорта. Внутри вендорского
// диапазона 9600-400K (почти его максимум), в отличие от 460800. Запас кольца
// по времени при этой скорости около 53 мс против 89 на 230400.
// ВАЖНО: значение обязано совпадать с P2P_BAUD в обоих скетчах.
// 24.09: ступень 600000 — делитель ровно 160 (96e6/600000), ошибка 0%.
// Запас кольца 34 мс против 44 на 460800. Критерий отката: потери чанков
// выше 1% или появление no skb / ovf в логе модуля.
// 23.09: ОБА МОДУЛЯ ПЕРЕШИТЫ НА 460800 (образ
// SDK/builds/APP_2.4.1.3-43933_2026-09-23_step3-460800-...bin, CRC 7e09).
// Вендор документирует 9600-400K, но делитель это держит с запасом: hguart.c
// считает apbclk/baud при apbclk=96 МГц, 96e6/460800=208, ошибка +0.16%;
// аппаратный потолок делителя — 6 Мбод. Настоящая цена — запас кольца
// (2 КБ, без управления потоком): 53 мс на 384000 против 44 мс на 460800.
// Откат: залить APP_..._2026-09-17_...384000... и вернуть P2P_BAUD в скетчах.
#define UART_P2P_BAUDRATE   3000000

// Окно в миллисекундах от старта модуля до захвата UART1 прозрачным режимом.
// Всё это время работают AT-команды. Нужно, чтобы успеть послать AT+NOP2P и
// тем самым отменить захват насовсем — иначе откатить прошивку можно было бы
// только вынув флеш-чип. См. комментарий к AT+NOP2P в atcmd.c.
// 8 секунд: с запасом на ручной ввод, но не настолько долго, чтобы мешать
// нормальной работе (видео всё равно стартует не мгновенно).
// 30000, а не 8000.
//
// 20.08. Найдено прямой проверкой: точка доступа, уже ушедшая в прозрачный
// режим, НЕ ПРИНИМАЕТ новые станции — она отвечает на запрос подключения
// деаутентификацией с причиной 2 ("предыдущая аутентификация недействительна").
// В логе камеры это выглядит так:
//     WPA_AUTHENTICATING -> WPA_ASSOCIATING
//     rx deauth from c6:e8:35:70:7a:68, reason:2
//     WPA_ASSOCIATING -> WPA_DISCONNECTED
// и дальше по кругу, AID=0, sta_list пуст.
//
// Отсюда весь день без связи: камера исправно передавала, радио работало, а
// линк рвала сама точка доступа через восемь секунд после своей загрузки.
// Раньше видео шло только потому, что камера успевала подключиться раньше.
//
// 30 секунд дают связи встать спокойно при любом порядке включения плат.
// Аварийное окно AT+NOP2P при этом становится только удобнее.
//
// ОСТАЁТСЯ ПРОВЕРИТЬ: сохраняет ли uart_p2p уже установленную ассоциацию или
// рвёт любую. Если рвёт — задержка не поможет, и вопрос переходит к самому
// прозрачному режиму на стороне AP.
// 120000 (две минуты), а не 30000.
//
// 25.08: тридцати секунд оказалось мало. Камера ищет сеть и повторяет попытки
// по своему графику, и попадёт ли она в окно — как повезёт: за два дня связь
// встала сама дважды, а в остальные разы не встала ни разу за двадцать минут.
//
// Две минуты — не рабочее значение, а доза для решающего опыта: дать связи
// встать ГАРАНТИРОВАННО до включения прозрачного режима и посмотреть, переживёт
// ли она сам момент включения.
//   переживёт -> диагноз закрыт, дальше подбираем разумную задержку (60-90 с)
//   порвётся  -> дело не в окне, а в самом uart_p2p на стороне точки доступа
// 30000: столько же, сколько в сборках delay30s, которые сейчас в обоих
// модулях. Значение обязано совпадать с MODULE_P2P_DELAY_MS в скетчах.
#define UART_P2P_START_DELAY_MS  30000



