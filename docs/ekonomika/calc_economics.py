def network():
    works = [dict(i=i, j=j, name=nm, t=t, tmin=t - 2, tmax=t + 3, who=who) for i, j, nm, t, who in WORKS]
    for w in works:
        assert (3 * w["tmin"] + 2 * w["tmax"]) / 5 == w["t"]
    arcs = [(w["i"], w["j"], w["t"]) for w in works] + [(i, j, t) for i, j, t in DUMMY]
    events = sorted({a for a, _, _ in arcs} | {b for _, b, _ in arcs})
    early = {}
    for e in events:
        early[e] = max([early[a] + t for a, b, t in arcs if b == e], default=0)
    T_cr = early[events[-1]]
    late = {e: T_cr for e in events}
    for e in reversed(events):
        late[e] = min([late[b] - t for a, b, t in arcs if a == e], default=T_cr)
    for w in works:
        w["R"] = late[w["j"]] - early[w["i"]] - w["t"]
        w["crit"] = w["R"] == 0
    par = []                                           # таблица 3.10 методички
    for a, b, t in arcs:
        par.append(dict(code=f"{a}–{b}", t=t, trn=early[a], tpn=late[b] - t, tro=early[a] + t,
                        tpo=late[b], R=late[b] - early[a] - t))
    crit = [e for e in events if early[e] == late[e]]
    return dict(works=works, events=events, early=early, late=late, T_cr=T_cr, crit_events=crit,
                params=par)


def int_shares(vals):
    """Доли в целых процентах с суммой 100 (метод наибольших остатков)."""
    tot = sum(vals)
    raw = [v / tot * 100 for v in vals]
    out = [int(x) for x in raw]
    for i in sorted(range(len(raw)), key=lambda i: raw[i] - out[i], reverse=True)[:100 - sum(out)]:
        out[i] += 1
    return out


def compute():
    r = {}
    sR = sum(x[1] for x in NTP)
    r["H_new"] = sum(x[1] * x[4] for x in NTP) / sR
    r["H_bases"] = [sum(x[1] * x[2 + b] for x in NTP) / sR for b in range(len(BASES))]
    r["J_bases"] = [round(r["H_new"] / h, 2) for h in r["H_bases"]]
    r["J"] = r["J_bases"][1]                      # для эффекта — относительно Wi-Fi 2,4 ГГц
    pts = dict(zip(NOVELTY_SCALE, NOVELTY_PTS))
    r["nov_sum"] = sum(pts[lvl] for _, lvl in NOVELTY)
    r["nov_max"] = 5 * len(NOVELTY)
    r["novelty"] = r["nov_sum"] / r["nov_max"]

    net = network()
    r["net"] = net
    r["T_cal"] = net["T_cr"]
    r["end"] = START + timedelta(days=r["T_cal"] - 1)
    assert r["end"] <= DEADLINE, r["end"]

    # трудоёмкость и зарплата по работам (как таблица 5 эталона)
    rows = []
    for k, w in enumerate(net["works"], 1):
        wd = w["t"]                                   # как в эталоне: трудоёмкость = t_ож
        w["wd"] = wd
        for who, cnt in w["who"].items():
            rows.append(dict(k=k, who=who, cnt=cnt, T=wd * cnt, rate=DAY_RATE[who],
                             zp=wd * cnt * DAY_RATE[who]))
    r["zp_rows"] = rows
    r["T_total"] = sum(x["T"] for x in rows)
    r["zp"] = sum(x["zp"] for x in rows)
    r["fot"] = round(r["zp"] * (1 + PREMIUM))
    r["soc"] = round(r["fot"] * SOC_RATE)
    r["comp_sum"] = sum(q * p for _, _, q, p in COMPONENTS)
    r["mat_sum"] = sum(q * p for _, _, q, p in MATERIALS)
    r["Z"] = round(r["fot"] / D_ZP)                   # укрупнённо по структуре затрат
    r["mat_share"] = (r["comp_sum"] + r["mat_sum"]) / r["Z"] * 100
    assert r["mat_share"] <= STRUCTURE[0][1], r["mat_share"]
    r["price"] = round(r["Z"] + r["fot"] * RHO_ZP)
    # ретрансляторы: дальность пролёта, число на оснащаемую протяжённость и затраты
    r["hop"] = {}
    for v, (_, L, f) in HOP.items():
        km = 10 ** ((L - 32.44 - 20 * math.log10(f)) / 20)
        r["hop"][v] = dict(L=L, km=round(km, 2))
    r["relay_cost"] = sum(q * c for _, q, c in RELAY)
    r["relays_base"] = math.ceil(ROUTE_KM / r["hop"]["Б"]["km"])
    r["relays_new"] = math.ceil(ROUTE_KM / r["hop"]["Н"]["km"])
    r["Z_base"] = r["relays_base"] * r["relay_cost"]
    r["Z_new"] = r["relays_new"] * r["relay_cost"]
    r["T_n"] = DEPLOY_YEARS
    r["E_eff"] = round((r["Z_base"] * r["J"] - r["Z_new"]) / r["T_n"])
    # доля разработчика — пропорционально затратам участников создания и применения [pan]
    r["alpha"] = round(r["Z"] / (r["Z"] + r["Z_new"]), 2)
    r["E_lvl"] = round(r["E_eff"] * r["alpha"] / r["price"], 2)
    r["T_ok"] = round(1 / r["E_lvl"], 2)
    r["T_ok_months"] = round(r["T_ok"] * 12)
    # длительность НИР при минимальных и максимальных оценках — наибольший путь графа
    for key, col in (("T_cr_min", "tmin"), ("T_cr_max", "tmax")):
        arcs = [(w["i"], w["j"], w[col]) for w in net["works"]] + DUMMY
        ev = {}
        for e in net["events"]:
            ev[e] = max([ev[a] + t for a, b, t in arcs if b == e], default=0)
        r[key] = ev[net["events"][-1]]
    r["period"] = (DEADLINE - START).days + 1
    assert r["T_cr_max"] <= r["period"], (r["T_cr_max"], r["period"])
    return r


