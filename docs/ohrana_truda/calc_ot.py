def eta_from_table(i, kss=KSS):
    """Линейная интерполяция по индексу помещения; возвращает η (доли), соседние i и их η, %."""
    row = ETA_KN[kss]
    lo = max(k for k in ETA_I if k <= i)
    hi = min(k for k in ETA_I if k >= i)
    a, b = row[ETA_I.index(lo)], row[ETA_I.index(hi)]
    u = a if lo == hi else a + (b - a) * (i - lo) / (hi - lo)
    return u / 100, (lo, a), (hi, b)


