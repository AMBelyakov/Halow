# ---------------------------------------------------------------- ЭМП стенда
F_HZ = 866e6                                      # центральная частота канала, Гц
P_TX_DBM = 20                                     # максимум AT+TXPOWER модуля TX-AH
G_DBI = 3.0                                       # усиление штыревой антенны (оценка)
R_M = 0.5                                         # расстояние антенна — оператор, м
PPE_POP = 10.0                                    # мкВт/см², ПДУ для населения, 0,3–300 ГГц
EE_WORK, T_SHIFT = 200.0, 8                       # (мкВт/см²)·ч, ч — ПДУ ЭЭ для работающих


def compute():
    r = {}
    S = ROOM_A * ROOM_B
    r["S"], r["V"] = S, S * ROOM_H
    r["S_per"], r["V_per"] = S / WORKERS, S * ROOM_H / WORKERS
    r["window"] = WINDOW_W * WINDOW_H

    # микроклимат: 1 — все показатели оптимальные, 2 — в допустимых пределах, 3.1 — выход за допустимые
    r["micro"] = {}
    for per, ((t0, t1), hum, v) in FACT.items():
        lo, hi, hlo, hhi, vmax = OPT[per]
        plo, phi, phlo, phhi, pv = PERM_NUM[per]
        r["micro"][per] = {"t_opt": lo <= t0 and t1 <= hi, "h_opt": hlo <= hum <= hhi, "v_opt": v <= vmax,
                           "perm": plo <= t0 and t1 <= phi and phlo <= hum <= phhi and v <= pv}
    mc = r["micro"].values()
    r["micro_class"] = (1 if all(d["t_opt"] and d["h_opt"] and d["v_opt"] for d in mc)
                        else 2 if all(d["perm"] for d in mc) else 3.1)

    # освещение: метод коэффициента использования светового потока
    r["h"] = ROOM_H - H_HANG - H_WORK
    r["i"] = S / (r["h"] * (ROOM_A + ROOM_B))
    r["E_exist"] = CHAND_N * CHAND_FLUX * ETA / (S * K_Z * Z)          # существующая люстра
    r["F_sum"] = E_GENERAL * S * K_Z * Z / ETA
    r["N_exact"] = r["F_sum"] / LUM_FLUX
    r["N"] = math.ceil(r["N_exact"])
    r["E_calc"] = r["N"] * LUM_FLUX * ETA / (S * K_Z * Z)
    r["P_spec"] = r["N"] * LUM_POWER / S
    r["light_class_before"] = 2 if r["E_exist"] >= E_GENERAL else 3.1
    r["light_class"] = 2 if r["E_calc"] >= E_GENERAL else 3.1

    # шум: энергетическое суммирование
    r["L_sum"] = 10 * math.log10(sum(10 ** (0.1 * L) for _, L in NOISE))

    # ЭМП: плотность потока энергии в дальней зоне
    r["lam"] = 3e8 / F_HZ
    r["P_w"] = 10 ** (P_TX_DBM / 10) / 1000
    r["G"] = 10 ** (G_DBI / 10)
    r["PPE_Wm2"] = r["P_w"] * r["G"] / (4 * math.pi * R_M ** 2)
    r["PPE"] = r["PPE_Wm2"] * 100                   # 1 Вт/м² = 100 мкВт/см²
    r["PPE_work"] = EE_WORK / T_SHIFT
    r["R_min"] = math.sqrt(r["P_w"] * r["G"] / (4 * math.pi * PPE_POP / 100))

    # угловой размер знака на экране, угловые минуты
    r["char_ang"] = 2 * math.degrees(math.atan(CHAR_H_MM / 2 / EYE_SCREEN_MM)) * 60

    # тяжесть и напряжённость
    r["heavy_class"] = max(c for _, _, c in HEAVINESS)
    tc = [c for _, items in TENSION for _, _, c in items]
    assert len(tc) == 23
    r["tension_counts"] = {k: tc.count(k) for k in (1, 2, 3.1, 3.2)}
    r["tension_class"] = tension_class(tc)
    return r


R = compute()

