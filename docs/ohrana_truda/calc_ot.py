def tension_class(classes):
    """Общая оценка напряжённости по Р 2.2.2006-05, п. 6.3."""
    n1, n2 = classes.count(1), classes.count(2)
    n31, n32 = classes.count(3.1), classes.count(3.2)
    n3 = n31 + n32
    if n3 == 0:
        return 1 if n1 >= 17 else 2
    if n3 <= 5:
        return 2
    if n32 > 6:
        return 3.3
    if (n31 == 6 and n32 == 0) or (3 <= n31 <= 5 and 1 <= n32 <= 3):
        return 3.1
    return 3.2


def compute():
    r = {}
    # помещение
    # 22.10: площади округлены до 0,1 м² до расчёта — подстановка чисел из текста даёт те же результаты
    r["S_main"] = round(MAIN_B * MAIN_A_LEFT + (MAIN_B - STEP_X) * (MAIN_A_RIGHT - MAIN_A_LEFT), 1)
    r["S_vest"] = round(VEST_B * VEST_A, 1)
    r["S"] = round(r["S_main"] + r["S_vest"], 1)
    r["V"] = r["S"] * ROOM_H
    r["S_per"] = r["S"] / WORKPLACES
    r["V_per"] = r["V"] / WORKPLACES
    r["window"] = WINDOW_W * WINDOW_H

    # микроклимат: 1 — все показатели оптимальные, 2 — в допустимых пределах, 3.1 — выход за допустимые
    r["micro"] = {}
    for per, ((t0, t1), hum, v) in FACT.items():
        lo, hi, hlo, hhi, vmax = OPT[per]
        plo, phi, phlo, phhi, pv = PERM_NUM[per]
        r["micro"][per] = {"t_opt": lo <= t0 and t1 <= hi, "h_opt": hlo <= hum <= hhi, "v_opt": v <= vmax,
                           "perm": plo <= t0 and t1 <= phi and phlo <= hum <= phhi and v <= pv}
    mc = r["micro"].values()
    r["micro_class"] = (1 if all(d["t_opt"] and d["h_opt"] and d["v_opt"] for d in mc)
                        else 2 if all(d["perm"] for d in mc) else 3.1)
    r["L_air"] = AIR_PER_PERSON * WORKERS[1]
    r["k_air"] = r["L_air"] / r["V"]

    # шум: эквивалентный уровень за смену с учётом времени действия источников
    r["noise"] = []
    acc = 0.0
    for name, L, t, cnt in NOISE:
        Lsrc = L + 10 * math.log10(cnt)
        Leq = Lsrc + 10 * math.log10(t / T_SHIFT)
        r["noise"].append((name, L, cnt, Lsrc, t, Leq))
        acc += 10 ** (0.1 * Leq)
    r["L_eq"] = 10 * math.log10(acc)
    r["noise_class"] = 2 if r["L_eq"] <= NOISE_PDU else 3.1

    # ЭМП стенда: ППЭ = N·P·G / (4πr²); 1 Вт/м² = 100 мкВт/см². ППЭ округляется до 0,1 до расчёта ЭЭ,
    # чтобы подстановка чисел из текста давала то же значение
    r["rf_P"] = 10 ** (RF_P_DBM / 10) / 1000                     # Вт
    r["rf_G"] = 10 ** (RF_G_DBI / 10)
    r["rf_PG"] = RF_BOARDS * r["rf_P"] * r["rf_G"]
    r["rf_lambda"] = 299.792458 / RF_F                           # м
    r["rf_ppe_w"] = r["rf_PG"] / (4 * math.pi * RF_R ** 2)       # Вт/м²
    r["rf_ppe"] = round(r["rf_ppe_w"] * 100, 1)                  # мкВт/см²
    r["rf_ee"] = r["rf_ppe"] * T_SHIFT
    r["rf_rmin"] = math.sqrt(r["rf_PG"] / (4 * math.pi * RF_EE_MAX / T_SHIFT / 100))
    r["rf_class"] = 2 if r["rf_ee"] <= RF_EE_MAX and r["rf_ppe"] <= RF_PPE_MAX else 3.1

    # освещение: метод коэффициента использования светового потока
    # 21.10: приведённая длина Г-образной основной части — её площадь, делённая на ширину
    r["A"] = r["S_main"] / MAIN_B
    r["B"] = MAIN_B
    r["h"] = ROOM_H - H_C - H_WORK
    r["i"] = r["A"] * r["B"] / (r["h"] * (r["A"] + r["B"]))
    eta, r["eta_lo"], r["eta_hi"] = eta_from_table(r["i"])
    r["eta"] = round(eta, 2)
    r["F_sum"] = E_NORM * r["S"] * K_Z * Z / r["eta"]
    r["N_exact"] = r["F_sum"] / NEW_FLUX
    # число светильников (кратно числу рядов) — наименьшее, при котором поток светильника
    # отклоняется от требуемого не более чем на −10…+20 %
    n_ = ROWS
    while (NEW_FLUX - r["F_sum"] / n_) / (r["F_sum"] / n_) * 100 < FLUX_TOL[0]:
        n_ += ROWS
    r["N"] = n_
    r["F_need"] = r["F_sum"] / r["N"]          # требуемый поток одного светильника
    r["dF"] = (NEW_FLUX - r["F_need"]) / r["F_need"] * 100
    r["per_row"] = r["N"] // ROWS
    r["E_new"] = r["N"] * NEW_FLUX * r["eta"] / (r["S"] * K_Z * Z)
    r["P_new"] = r["N"] * NEW_P
    r["p_spec"] = r["P_new"] / r["S"]
    r["L_B"] = r["B"] / ROWS                   # между рядами
    r["l_B"] = r["L_B"] / 2                    # от крайнего ряда до стены
    r["L_A"] = MAIN_A_LEFT / r["per_row"]      # между светильниками в ряду (по короткой левой стене)
    r["l_A"] = r["L_A"] / 2
    assert r["N"] == INST_N, (r["N"], INST_N)   # расчёт должен совпасть с установленными
    # 23.10: отклонение — от освещённости, округлённой как в тексте (287 лк): (287 − 300) / 300
    r["dE"] = (round(r["E_new"]) - E_NORM) / E_NORM * 100
    r["E_init"] = r["N"] * NEW_FLUX * r["eta"] / (r["S"] * Z)   # без коэффициента запаса
    r["light_class"] = 2 if FLUX_TOL[0] <= r["dE"] <= FLUX_TOL[1] or r["E_new"] >= E_NORM else 3.1

    # тяжесть и напряжённость
    r["heavy_class"] = max(c for _, _, c in HEAVINESS)
    tc = [c for _, items in TENSION for _, _, c in items]
    assert len(tc) == 23
    r["tension_counts"] = {k: tc.count(k) for k in (1, 2, 3.1, 3.2)}
    r["tension_class"] = tension_class(tc)

    r["final"] = max(r["micro_class"], r["light_class"], r["noise_class"], r["rf_class"],
                     r["heavy_class"], r["tension_class"], 2)
    return r


