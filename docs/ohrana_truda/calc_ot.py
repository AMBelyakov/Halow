def tension_class(classes):
    """Общая оценка напряжённости по Р 2.2.2006-05, п. 6.3."""
    n1, n2 = classes.count(1), classes.count(2)
    n31, n32 = classes.count(3.1), classes.count(3.2)
    n3 = n31 + n32
    if n3 == 0:
        return 1 if n1 >= 17 else 2
    if n3 <= 5:
        return 2
    if n32 > 6:
        return 3.3
    if (n31 == 6 and n32 == 0) or (3 <= n31 <= 5 and 1 <= n32 <= 3):
        return 3.1
    return 3.2


def compute():
    r = {}
    # помещение
    r["S_main"] = MAIN_B * MAIN_A_LEFT + (MAIN_B - STEP_X) * (MAIN_A_RIGHT - MAIN_A_LEFT)
    r["S_vest"] = VEST_B * VEST_A
    r["S"] = r["S_main"] + r["S_vest"]
    r["V"] = r["S"] * ROOM_H
    r["S_per"] = r["S"] / WORKPLACES
    r["V_per"] = r["V"] / WORKPLACES
    r["window"] = WINDOW_W * WINDOW_H

    # микроклимат: 1 — все показатели оптимальные, 2 — в допустимых пределах, 3.1 — выход за допустимые
    r["micro"] = {}
    for per, ((t0, t1), hum, v) in FACT.items():
        lo, hi, hlo, hhi, vmax = OPT[per]
        plo, phi, phlo, phhi, pv = PERM_NUM[per]
        r["micro"][per] = {"t_opt": lo <= t0 and t1 <= hi, "h_opt": hlo <= hum <= hhi, "v_opt": v <= vmax,
                           "perm": plo <= t0 and t1 <= phi and phlo <= hum <= phhi and v <= pv}
    mc = r["micro"].values()
    r["micro_class"] = (1 if all(d["t_opt"] and d["h_opt"] and d["v_opt"] for d in mc)
                        else 2 if all(d["perm"] for d in mc) else 3.1)
    r["L_air"] = AIR_PER_PERSON * WORKERS[1]
    r["k_air"] = r["L_air"] / r["V"]

    # шум: эквивалентный уровень за смену с учётом времени действия источников
    r["noise"] = []
    acc = 0.0
    for name, L, t, cnt in NOISE:
        Lsrc = L + 10 * math.log10(cnt)
        Leq = Lsrc + 10 * math.log10(t / T_SHIFT)
        r["noise"].append((name, L, cnt, Lsrc, t, Leq))
        acc += 10 ** (0.1 * Leq)
    r["L_eq"] = 10 * math.log10(acc)
    r["noise_class"] = 2 if r["L_eq"] <= NOISE_LIMIT else 3.1

    # освещение: метод коэффициента использования светового потока
    r["A"] = MAIN_A_RIGHT                      # длина основной части по правой стене
    r["B"] = MAIN_B
    r["h"] = ROOM_H - H_C - H_WORK
    r["i"] = r["A"] * r["B"] / (r["h"] * (r["A"] + r["B"]))
    r["F_sum"] = E_NORM * r["S"] * K_Z * Z / NEW_ETA
    r["N_exact"] = r["F_sum"] / NEW_FLUX
    r["N"] = math.ceil(r["N_exact"])
    if r["N"] % ROWS:
        r["N"] += ROWS - r["N"] % ROWS
    r["per_row"] = r["N"] // ROWS
    r["E_new"] = r["N"] * NEW_FLUX * NEW_ETA / (r["S"] * K_Z * Z)
    r["P_new"] = r["N"] * NEW_P
    r["p_spec"] = r["P_new"] / r["S"]
    r["L_B"] = r["B"] / ROWS                   # между рядами
    r["l_B"] = r["L_B"] / 2                    # от крайнего ряда до стены
    r["L_A"] = MAIN_A_LEFT / r["per_row"]      # между светильниками в ряду (по короткой левой стене)
    r["l_A"] = r["L_A"] / 2
    r["lam"] = max(r["L_B"], r["L_A"]) / r["h"]
    assert r["N"] == INST_N, (r["N"], INST_N)   # расчёт должен совпасть с установленными
    r["light_class"] = 2 if r["E_new"] >= E_NORM else 3.1

    # тяжесть и напряжённость
    r["heavy_class"] = max(c for _, _, c in HEAVINESS)
    tc = [c for _, items in TENSION for _, _, c in items]
    assert len(tc) == 23
    r["tension_counts"] = {k: tc.count(k) for k in (1, 2, 3.1, 3.2)}
    r["tension_class"] = tension_class(tc)

    r["final"] = max(r["micro_class"], r["light_class"], r["noise_class"],
                     r["heavy_class"], r["tension_class"], 2)
    return r


