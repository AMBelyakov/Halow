# ----------------------------------------------------------------------- помощники
def no_highlight(el):
    for h in el.iter(qn("w:highlight")):
        h.getparent().remove(h)


def set_par(p, text):
    """Текст абзаца с форматом первого прогона; подсветка шаблона снимается."""
    runs = p.runs
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)
    no_highlight(p._p)


def set_cell(cell, text):
    ps = cell.paragraphs
    set_par(ps[0], text)
    for p in ps[1:]:
        p._p.getparent().remove(p._p)


def body_par(text_parts, bold=False, indent=True, align="both", size=28, keep=False):
    """Абзац отчёта: 14 пт, полуторный интервал, по ширине, отступ 1,25 см."""
    p = OxmlElement("w:p")
    ppr = OxmlElement("w:pPr")
    if keep:
        ppr.append(OxmlElement("w:keepNext"))
    sp = OxmlElement("w:spacing")
    sp.set(qn("w:line"), "360")
    sp.set(qn("w:lineRule"), "auto")
    ppr.append(sp)
    if indent:
        ind = OxmlElement("w:ind")
        ind.set(qn("w:firstLine"), "709")
        ppr.append(ind)
    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), align)
    ppr.append(jc)
    p.append(ppr)
    if isinstance(text_parts, str):
        text_parts = [(text_parts, bold)]
    for txt, b in text_parts:
        r = OxmlElement("w:r")
        rpr = OxmlElement("w:rPr")
        if b:
            rpr.append(OxmlElement("w:b"))
        sz = OxmlElement("w:sz")
        sz.set(qn("w:val"), str(size))
        rpr.append(sz)
        r.append(rpr)
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = txt
        r.append(t)
        p.append(r)
    return p


class Inserter:
    """Вставка элементов подряд после опорного элемента."""

    def __init__(self, anchor):
        self.last = anchor

    def add(self, el):
        self.last.addnext(el)
        self.last = el
        return el

    def par(self, *a, **k):
        return self.add(body_par(*a, **k))

    def head(self, text):
        return self.par(text, bold=True, indent=False, align="left", keep=True)

    def dash(self, text):
        return self.par("– " + text)

    def table(self, caption, widths_mm, rows, size=22):
        self.par(caption, indent=False, align="left", keep=True)
        t = d.add_table(rows=len(rows), cols=len(widths_mm))
        t.style = d.styles["Table Grid"]
        for ri, row in enumerate(rows):
            for ci, val in enumerate(row):
                c = t.cell(ri, ci)
                c.width = Mm(widths_mm[ci])
                pp = c.paragraphs[0]
                run = pp.add_run(val)
                run.font.size = Pt(size / 2)
                run.bold = ri == 0
                if ri == 0:
                    pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
            trpr = t.rows[ri]._tr.get_or_add_trPr()
            trpr.append(OxmlElement("w:cantSplit"))
            if ri == 0:
                th = OxmlElement("w:tblHeader")
                th.set(qn("w:val"), "true")
                trpr.append(th)
        self.add(t._tbl)
        self.par("", indent=False)

    def figure(self, path, caption, width_mm):
        pic = d.add_paragraph()
        pic.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pic.paragraph_format.keep_with_next = True
        pic.add_run().add_picture(path, width=Mm(width_mm))
        self.add(pic._p)
        self.par(caption, indent=False, align="center")


