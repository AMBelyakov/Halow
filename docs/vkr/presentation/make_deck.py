def range_fs(L, f):
    return 10 ** ((L - 32.44 - 20 * math.log10(f)) / 20) * 1000


def range_2ray(L, f, h1, h2):
    b = 4 * h1 * h2 / (299.792458 / f)
    return range_fs(L, f) if fspl(b, f) >= L else b * 10 ** ((L - fspl(b, f)) / 40)


