def table(rows, widths, size=28, hl_col=None):
    out = [f'<table style="font-size:{size}px; color:{DARK}; {FONT}">']
    for ri, r in enumerate(rows):
        tag = "th" if ri == 0 else "td"
        cells = []
        for ci, c in enumerate(r):
            st = []
            if ri == 0:
                st.append(f"width:{widths[ci]}%")
            if ci > 0:
                st.append("text-align:center")
            if hl_col is not None and ci == hl_col:
                st.append(f"color:{BLUE_T}")
            cells.append(f'<{tag} style="{"; ".join(st)}">{c}</{tag}>')
        bgr = f' style="background:{"#E4E1D8" if ri == 0 else "#FDFCFA"}"'
        out.append(f"<tr{bgr}>" + "".join(cells) + "</tr>")
    out.append("</table>")
    return "\n".join(out)


