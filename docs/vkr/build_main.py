def fspl(d_m, f_mhz=F_HALOW):
    return 20 * math.log10(d_m / 1000) + 20 * math.log10(f_mhz) + 32.44


def d_bp(h1, h2, lam=LAM):
    return 4 * h1 * h2 / lam


def dual_slope(d_m, h1, h2):
    b = d_bp(h1, h2)
    return fspl(d_m) if d_m <= b else fspl(b) + 40 * math.log10(d_m / b)


def noise(b_hz):
    return -174 + 10 * math.log10(b_hz)


def fresnel_mid(d_m, lam=LAM):
    return 0.5 * math.sqrt(lam * d_m)


def chunk_rate(baud, gap_ms, payload=1400, hdr=20):
    """Полезная скорость провода, Мбит/с: чанк (payload+hdr) в 8N1 плюс пауза."""
    t = (payload + hdr) * 10 / baud * 1000 + gap_ms
    return payload * 8 / t / 1000


