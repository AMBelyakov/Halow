def finalize(out):
    order = {}
    tok = re.compile(r"\[@([^\]]+)\]")

    def repl(mo):
        keys = [k.strip().lstrip("@") for k in mo.group(1).split(";")]
        nums = []
        for k in keys:
            if k not in SOURCES:
                raise KeyError(f"нет источника «{k}»")
            order.setdefault(k, len(order) + 1)
            nums.append(order[k])
        return "[" + ", ".join(str(x) for x in nums) + "]"

    for t in D.doc.element.body.iter(qn("w:t")):
        if t.text and "[@" in t.text:
            t.text = tok.sub(repl, t.text)
    D.H("Список использованных источников", 1).paragraph_format.page_break_before = True
    for k, num in sorted(order.items(), key=lambda kv: kv[1]):
        D.para(f"{num}. {SOURCES[k]}", indent=False, align=LEFT)
    D.doc.save(out)
    return order, set(SOURCES) - set(order)


order, unused = finalize(OUT)
