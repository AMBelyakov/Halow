def range_fs(L, f_mhz):
    """Расстояние, м, на котором потери в свободном пространстве равны L."""
    return 10 ** ((L - 32.44 - 20 * math.log10(f_mhz)) / 20) * 1000


def range_2ray(L, f_mhz, h1, h2):
    """Расстояние, м, на котором потери двухсегментной двухлучевой модели равны L."""
    b = 4 * h1 * h2 / (299.792458 / f_mhz)
    lb = fspl(b, f_mhz)
    return range_fs(L, f_mhz) if lb >= L else b * 10 ** ((L - lb) / 40)


