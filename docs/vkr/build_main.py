def chunk_rate(baud, gap_ms, payload=FRAG_PAYLOAD, hdr=FRAG_HDR):
    """Полезная скорость линии UART, Мбит/с: фрагмент (payload+hdr) в 8N1 плюс пауза."""
    t = (payload + hdr) * 10 / baud * 1000 + gap_ms
    return payload * 8 / t / 1000


