def foliage_db(d, f_ghz):
    """Модель Вайсбергера: затухание на участке трассы через лес длиной d, м."""
    return 0.45 * f_ghz ** 0.284 * d if d <= 14 else 1.33 * f_ghz ** 0.284 * d ** 0.588


