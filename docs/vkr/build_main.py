def finalize(out):
    """Ссылки — сквозные номера ВКР (docx_common.number_refs). Список включает источники
    всех глав, в т.ч. экономической части и охраны труда, в порядке sources_order.json."""
    cited = number_refs(D.doc, SOURCES, "main")
    all_src = {**SOURCES_OT, **SOURCES_ECON, **SOURCES}
    try:
        with open(ORDER_FILE, encoding="utf-8") as f:
            num = json.load(f)
    except FileNotFoundError:
        num = {}
    for k in cited:                      # без build_all.py — хотя бы источники этой части
        num.setdefault(k, max(num.values(), default=0) + 1)
    D.H("Список использованных источников", 1).paragraph_format.page_break_before = True
    for k, x in sorted(num.items(), key=lambda kv: kv[1]):
        D.para(f"{x}. {all_src[k]}", indent=False, align=LEFT)
    D.doc.save(out)
    return cited, set(SOURCES) - set(cited), len(num)


